"""Generates the Twelve Testers icon in every format from one geometry.

Glyph: 12 dots in a ring (twelve testers) around a check mark (test passed).
Outputs Android vector drawables into app/src/main/res and SVGs into store-listing/src.
Run from the project root: python store-listing/src/make_icon.py
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "app/src/main/res/drawable"
SRC = ROOT / "store-listing/src"

# Geometry on the 108x108 adaptive-icon canvas (safe zone = 66dp circle).
C = 54.0
RING_R = 24.0
DOT_R = 2.7
CHECK = [(42.5, 54.5), (50.5, 62.5), (66.0, 46.5)]
CHECK_W = 6.5

INDIGO, VIOLET, PINK = "#4F46E5", "#9333EA", "#EC4899"


def dots(scale=1.0, cx=C, cy=C):
    out = []
    for i in range(12):
        a = -math.pi / 2 + i * math.pi / 6
        out.append((cx + RING_R * scale * math.cos(a), cy + RING_R * scale * math.sin(a)))
    return out


def circle_path(x, y, r):
    return f"M{x - r:.3f},{y:.3f}a{r:.3f},{r:.3f} 0 1,0 {2 * r:.3f},0a{r:.3f},{r:.3f} 0 1,0 {-2 * r:.3f},0z"


def check_path(scale=1.0, cx=C, cy=C):
    pts = [(cx + (x - C) * scale, cy + (y - C) * scale) for x, y in CHECK]
    return "M" + "L".join(f"{x:.3f},{y:.3f}" for x, y in pts)


def glyph_vector(color, viewport=108.0):
    s = viewport / 108.0
    c = viewport / 2
    dot_paths = "".join(circle_path(x, y, DOT_R * s) for x, y in dots(s, c, c))
    return f"""    <path
        android:fillColor="{color}"
        android:pathData="{dot_paths}" />
    <path
        android:strokeColor="{color}"
        android:strokeWidth="{CHECK_W * s:.3f}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:pathData="{check_path(s, c, c)}" />"""


def vector(viewport, body, size_dp=None):
    size = size_dp or viewport
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by store-listing/src/make_icon.py — edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="{size:g}dp"
    android:height="{size:g}dp"
    android:viewportWidth="{viewport:g}"
    android:viewportHeight="{viewport:g}">
{body}
</vector>
"""


BACKGROUND = f"""    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="108"
                android:endY="108">
                <item android:color="#FF{INDIGO[1:]}" android:offset="0.0" />
                <item android:color="#FF{VIOLET[1:]}" android:offset="0.55" />
                <item android:color="#FF{PINK[1:]}" android:offset="1.0" />
            </gradient>
        </aapt:attr>
    </path>
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="radial"
                android:centerX="30"
                android:centerY="26"
                android:gradientRadius="70">
                <item android:color="#33FFFFFF" android:offset="0.0" />
                <item android:color="#00FFFFFF" android:offset="1.0" />
            </gradient>
        </aapt:attr>
    </path>"""


def svg_glyph(scale, color="#FFFFFF"):
    d = "".join(f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{DOT_R * scale:.2f}"/>' for x, y in dots(scale))
    return (f'<g fill="{color}">{d}</g>'
            f'<path d="{check_path(scale)}" fill="none" stroke="{color}" stroke-width="{CHECK_W * scale:.2f}" '
            f'stroke-linecap="round" stroke-linejoin="round"/>')


def svg_icon(glyph_scale=1.3, rounded=False):
    """Full-bleed square icon (Play Store applies its own mask)."""
    rx = ' rx="24"' if rounded else ""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="{INDIGO}"/><stop offset=".55" stop-color="{VIOLET}"/><stop offset="1" stop-color="{PINK}"/>
    </linearGradient>
    <radialGradient id="hl" cx="30" cy="26" r="70" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#fff" stop-opacity=".2"/><stop offset="1" stop-color="#fff" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="108" height="108"{rx} fill="url(#bg)"/>
  <rect width="108" height="108"{rx} fill="url(#hl)"/>
  {svg_glyph(glyph_scale)}
</svg>
"""


if __name__ == "__main__":
    (RES / "ic_launcher_background.xml").write_text(vector(108, BACKGROUND), encoding="utf-8")
    (RES / "ic_launcher_foreground.xml").write_text(vector(108, glyph_vector("#FFFFFFFF")), encoding="utf-8")
    # Notification icon: same glyph enlarged to fill the 24dp status-bar slot.
    notif = ('    <group android:pivotX="54" android:pivotY="54" android:scaleX="1.9" android:scaleY="1.9">\n'
             + glyph_vector("#FFFFFFFF") + "\n    </group>")
    (RES / "ic_notification.xml").write_text(vector(108, notif, size_dp=24), encoding="utf-8")
    SRC.mkdir(parents=True, exist_ok=True)
    (SRC / "icon.svg").write_text(svg_icon(), encoding="utf-8")
    (SRC / "icon-rounded.svg").write_text(svg_icon(rounded=True), encoding="utf-8")
    (SRC / "glyph-white.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">{svg_glyph(1.0)}</svg>\n', encoding="utf-8")
    print("icon assets written")
